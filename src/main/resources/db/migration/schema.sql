-- =========================================
-- 1. USUARIO
-- =========================================

CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(100) NOT NULL,
                         usuario VARCHAR(50) NOT NULL UNIQUE,
                         senha VARCHAR(255) NOT NULL,
                         adm_flag BOOLEAN NOT NULL DEFAULT FALSE
);


-- =========================================
-- 2. CUPCAKE
-- =========================================

CREATE TABLE cupcake (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(100) NOT NULL,
                         estoque INTEGER NOT NULL DEFAULT 0,
                         descricao VARCHAR(1000),
                         preco_unitario DECIMAL(10,2) NOT NULL,

                         CONSTRAINT chk_cupcake_estoque
                             CHECK (estoque >= 0),

                         CONSTRAINT chk_cupcake_preco
                             CHECK (preco_unitario >= 0)
);


-- =========================================
-- 3. CUPCAKE_IMAGE
-- =========================================

CREATE TABLE cupcake_image (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               id_cupcake BIGINT NOT NULL,
                               caminho VARCHAR(500) NOT NULL,
                               is_thumbnail BOOLEAN NOT NULL DEFAULT FALSE,
                               ordem INTEGER NOT NULL DEFAULT 0,

                               CONSTRAINT fk_cupcake_image
                                   FOREIGN KEY (id_cupcake)
                                       REFERENCES cupcake(id),

                               CONSTRAINT chk_cupcake_image_ordem
                                   CHECK (ordem >= 0)
);

CREATE INDEX idx_cupcake_image_cupcake
    ON cupcake_image(id_cupcake);


-- =========================================
-- 4. INGREDIENTE
-- =========================================

CREATE TABLE ingrediente (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             descricao VARCHAR(255) NOT NULL
);


-- =========================================
-- 5. ENCOMENDA
-- =========================================

CREATE TABLE encomenda (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           data_retirada TIMESTAMP,
                           previsao_retirada TIMESTAMP,
                           data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           preco_total DECIMAL(10,2) NOT NULL DEFAULT 0.00,
                           id_usuario BIGINT NOT NULL,

                           CONSTRAINT fk_encomenda_usuario
                               FOREIGN KEY (id_usuario)
                                   REFERENCES usuario(id),

                           CONSTRAINT chk_encomenda_preco
                               CHECK (preco_total >= 0)
);


-- =========================================
-- 6. CUPCAKE_INGREDIENTES
-- =========================================

CREATE TABLE cupcake_ingredientes (
                                      id_cupcake BIGINT NOT NULL,
                                      id_ingrediente BIGINT NOT NULL,

                                      CONSTRAINT pk_cupcake_ingredientes
                                          PRIMARY KEY (id_cupcake, id_ingrediente),

                                      CONSTRAINT fk_ci_cupcake
                                          FOREIGN KEY (id_cupcake)
                                              REFERENCES cupcake(id),

                                      CONSTRAINT fk_ci_ingrediente
                                          FOREIGN KEY (id_ingrediente)
                                              REFERENCES ingrediente(id)
);


-- =========================================
-- 7. ENCOMENDA_CUPCAKES
-- =========================================

CREATE TABLE encomenda_cupcakes (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    id_encomenda BIGINT NOT NULL,
                                    id_cupcake BIGINT NOT NULL,
                                    tamanho VARCHAR(30) NOT NULL,
                                    quantidade INTEGER NOT NULL,
                                    preco_unitario DECIMAL(10,2) NOT NULL,

                                    CONSTRAINT fk_ec_encomenda
                                        FOREIGN KEY (id_encomenda)
                                            REFERENCES encomenda(id),

                                    CONSTRAINT fk_ec_cupcake
                                        FOREIGN KEY (id_cupcake)
                                            REFERENCES cupcake(id),

                                    CONSTRAINT uk_ec_item
                                        UNIQUE (id_encomenda, id_cupcake, tamanho),

                                    CONSTRAINT chk_ec_quantidade
                                        CHECK (quantidade > 0),

                                    CONSTRAINT chk_ec_preco
                                        CHECK (preco_unitario >= 0)
);